#!/bin/bash
# Shared configuration. Runtime state and registries must stay out of version control.
ORCH_HOME=${ORCH_HOME:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}
ORCH_WORKERS=${ORCH_WORKERS:-$ORCH_HOME/workers.tsv}
ORCH_STATE_DIR=${ORCH_STATE_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/orch-heartbeat}
ORCH_TERMINAL_TITLE=${ORCH_TERMINAL_TITLE:-orchestrator}
ORCH_TRANSCRIPT_DIR=${ORCH_TRANSCRIPT_DIR:-$ORCH_HOME/transcripts}
ORCH_ORCA=${ORCH_ORCA:-orca}
ORCH_HUMAN_QUEUE=${ORCH_HUMAN_QUEUE:-}
ORCH_BACKUP_UNIT=${ORCH_BACKUP_UNIT:-}
ORCH_BACKUP_TIMER=${ORCH_BACKUP_TIMER:-}
ORCH_INBOX_DIR=${ORCH_INBOX_DIR:-}
ORCH_CAPACITY_MAX=${ORCH_CAPACITY_MAX:-10}
ORCH_POLL_SECONDS=${ORCH_POLL_SECONDS:-60}
ORCH_COMPACT_BYTES=${ORCH_COMPACT_BYTES:-1500000}
mkdir -p "$ORCH_STATE_DIR"
orca() { "$ORCH_ORCA" "$@"; }
export ORCH_HOME ORCH_WORKERS ORCH_STATE_DIR ORCH_ORCA ORCH_TERMINAL_TITLE
export ORCH_TRANSCRIPT_DIR ORCH_HUMAN_QUEUE ORCH_BACKUP_UNIT ORCH_BACKUP_TIMER ORCH_INBOX_DIR
export ORCH_CAPACITY_MAX ORCH_POLL_SECONDS ORCH_COMPACT_BYTES
